CREATE DATABASE IF NOT EXISTS ticket_analytics;
USE ticket_analytics;

CREATE TABLE IF NOT EXISTS categories  (id INT PRIMARY KEY, name VARCHAR(50) NOT NULL);
CREATE TABLE IF NOT EXISTS technicians (id INT PRIMARY KEY, name VARCHAR(80) NOT NULL);
CREATE TABLE IF NOT EXISTS tickets (
  ticket_id     INT PRIMARY KEY,
  title         VARCHAR(120) NOT NULL,
  created_at    DATETIME NOT NULL,
  closed_at     DATETIME NULL,
  category_id   INT NOT NULL,
  priority      ENUM('Low','Medium','High') NOT NULL,
  status        ENUM('Open','In progress','Closed') NOT NULL,
  department    VARCHAR(60),
  technician_id INT,
  FOREIGN KEY (category_id)   REFERENCES categories(id),
  FOREIGN KEY (technician_id) REFERENCES technicians(id)
);

